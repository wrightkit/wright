// Generates the TypeScript types of `wright-agent/v1` shipped in the
// `@wrightkit/core` npm package (#960, ADR-0037 decision 5) from the
// committed schema — never hand-written.
//
//   node scripts/generate-core-types.ts            write the committed file
//   node scripts/generate-core-types.ts --check    fail when it is stale

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'
import type { JSONSchema } from 'json-schema-to-typescript'

const scriptsDir = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(scriptsDir, '..')
const schemaPath = join(repoRoot, 'schemas/wright-agent-v1.schema.json')
const committedPath = join(
  repoRoot,
  'crates/wright-wasm/js/generated/wright-agent-v1.d.ts',
)

const STYLE = { semi: false, singleQuote: true }

// The root compiles to the request/response pair a consumer sees; every
// $defs entry compiles to its own named export.
function agentEnvelope(schema: JSONSchema): JSONSchema {
  const { $ref, ...rest } = schema
  return {
    ...rest,
    type: 'object',
    required: ['request', 'response'],
    additionalProperties: false,
    properties: {
      request: {
        $ref: '#/$defs/ToolRequest',
        description: 'A wright-agent/v1 request body.',
      },
      response: {
        $ref: '#/$defs/ToolResponse',
        description: 'A wright-agent/v1 result envelope.',
      },
    },
  }
}

interface RefAliasDef {
  $ref?: string
  description?: string
  [key: string]: unknown
}

function refAliases(schema: JSONSchema) {
  const defs = (schema as { $defs?: Record<string, RefAliasDef> }).$defs ?? {}
  return Object.entries(defs)
    .filter(([, def]) => {
      const keys = Object.keys(def).filter((key) => key !== 'description')
      return keys.length === 1 && def.$ref?.startsWith('#/$defs/')
    })
    .map(([name, def]) => ({
      name,
      target: def.$ref!.slice('#/$defs/'.length),
      description: def.description,
    }))
}

export async function generateCoreTypes(): Promise<string> {
  const schema = agentEnvelope(
    JSON.parse(readFileSync(schemaPath, 'utf8')) as JSONSchema,
  )
  const banner = `/**
 * Generated by scripts/generate-core-types.ts — do not edit.
 * Source: schemas/wright-agent-v1.schema.json
 */`
  let body = await compile(schema, 'ToolContract', {
    bannerComment: banner,
    unreachableDefinitions: true,
    style: STYLE,
  })
  body = body.replaceAll(
    /\/\*\*\n \* This interface was referenced by[^\n]*\n \* via the `definition` "[^"]+"\.\n \*\/\n/g,
    '',
  )
  for (const alias of refAliases(schema)) {
    if (alias.description) {
      body += `/**\n * ${alias.description.replaceAll('*/', '*\\/')}\n */\n`
    }
    body += `export type ${alias.name} = ${alias.target}\n`
  }
  return body.endsWith('\n') ? body : `${body}\n`
}

async function main() {
  const check = process.argv.includes('--check')
  const generated = await generateCoreTypes()
  if (check) {
    let committed: string | null = null
    try {
      committed = readFileSync(committedPath, 'utf8')
    } catch {
      committed = null
    }
    if (committed !== generated) {
      console.error(
        `${committedPath} is stale; run \`node scripts/generate-core-types.ts\``,
      )
      process.exit(1)
    }
    console.log('generated core types are up to date')
    return
  }
  mkdirSync(dirname(committedPath), { recursive: true })
  writeFileSync(committedPath, generated)
  console.log(`wrote ${committedPath}`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main()
}
